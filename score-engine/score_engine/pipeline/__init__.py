"""声明式数据接入管道（Data Pipeline）。

背景（对齐 issue #8 最新追评）：用户不希望每次都由 NPC "人肉单次驱动"——
即每次都要重新识别"这份数据该从哪来、该按什么规则存进哪张库哪张表"。
那样既不专业也不可持续，无法随仓库演进沉淀"如何正确入库"的规则。

本管道用 **一份声明文件 + 一条复用命令** 把"如何接入真实数据"固化下来：

    MANIFEST.json   —— 声明每个数据源：原始文件 → 字段映射 → 目标表位
                          → 清洗/校验/去重规则 → 溯源标记（source/年份/置信）。
    ingest 命令     —— 读取 manifest + 原始数据文件，按声明规则**自动分类并落库**，
                          产出"质检报告"，全程无需人肉判断。

由此获得**复用能力**：以后补充某类数据，只需
    1) 把原始文件放进 data_sources/ 对应子目录；
    2) 在 MANIFEST.json 里登记一条 source（声明字段映射与规则）；
    3) 运行 `cli ingest`。
数据会按规则自动落到正确库位，越补越全、越补越准，持续提升数据质量。
"""
